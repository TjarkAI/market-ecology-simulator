"""The Dock launcher.

`Marktstadt.app` is a folder with a plist, a bash script and an icon, generated by
`scripts/build_app.py`. Nothing about it is compiled, so nothing about it fails
loudly — a bundle whose launcher no longer finds the project, or whose plist points
at an executable that is not there, looks exactly like a working one until it is
double-clicked. These tests double-click it on paper.

The one real defect found while building it is pinned below: killing the old server
with a bare `lsof -ti tcp:8000` also matches every *client* holding a connection to
that port, so the second launch shot down the networking process of the browser
showing the town.
"""

from __future__ import annotations

import plistlib
import re
import stat
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "Marktstadt.app"
CONTENTS = APP / "Contents"

pytestmark = pytest.mark.skipif(
    not APP.exists(),
    reason="Marktstadt.app nicht gebaut — python scripts/build_app.py",
)


def launcher_source() -> str:
    return (CONTENTS / "MacOS" / "Marktstadt").read_text(encoding="utf-8")


def test_the_bundle_has_the_three_parts_macos_requires():
    assert (CONTENTS / "Info.plist").is_file()
    assert (CONTENTS / "MacOS" / "Marktstadt").is_file()
    assert (CONTENTS / "Resources" / "Marktstadt.icns").is_file()


def test_the_plist_points_at_files_that_exist():
    """`CFBundleExecutable` and `CFBundleIconFile` are names, not paths, and a typo
    in either produces a bundle that opens and does nothing."""
    plist = plistlib.loads((CONTENTS / "Info.plist").read_bytes())
    assert (CONTENTS / "MacOS" / plist["CFBundleExecutable"]).is_file()
    assert (CONTENTS / "Resources" / f"{plist['CFBundleIconFile']}.icns").is_file()
    assert plist["CFBundlePackageType"] == "APPL"
    assert plist["NSHighResolutionCapable"] is True


def test_the_launcher_is_executable():
    mode = (CONTENTS / "MacOS" / "Marktstadt").stat().st_mode
    assert mode & stat.S_IXUSR, "ohne Ausführungsrecht startet der Doppelklick nichts"


@pytest.mark.skipif(sys.platform != "darwin", reason="bash/macOS")
def test_the_launcher_is_valid_shell():
    result = subprocess.run(["bash", "-n", str(CONTENTS / "MacOS" / "Marktstadt")],
                            capture_output=True, text=True)
    assert result.returncode == 0, result.stderr


def test_the_launcher_only_kills_the_listening_server():
    """The defect that cost a browser during testing.

    `lsof -ti tcp:8000` lists every process with a connection on that port, clients
    included. Without `-sTCP:LISTEN` the second launch kills the browser that is
    displaying the town.
    """
    # Whole lines, and comments dropped first — the comment explaining this rule
    # naturally contains both "lsof" and the word Client.
    calls = [line for line in launcher_source().splitlines()
             if "lsof" in line and not line.lstrip().startswith("#")]
    assert calls, "der Starter räumt den Port nicht mehr frei"
    for line in calls:
        assert "-sTCP:LISTEN" in line, (
            f"lsof ohne -sTCP:LISTEN trifft auch Clients: {line.strip()}")


def test_the_launcher_checks_for_the_project_before_starting():
    """It resolves the project relative to itself. If that lands somewhere without
    the project it has to say so, not open an empty Terminal."""
    source = launcher_source()
    assert "mes/api.py" in source and "start.sh" in source, \
        "der Starter prüft nicht, ob er im Projektordner liegt"
    assert "display alert" in source, "ohne Projekt fehlt die Rückmeldung"
    assert "MES_HOME" in source, "kein Override für eine App außerhalb des Projekts"


def test_the_launcher_runs_the_same_entry_point_as_the_command_line():
    """One way in. If the app started uvicorn itself it would drift from start.sh —
    which is where the virtual environment and the dependency install live."""
    assert "./start.sh" in launcher_source()


def test_the_icon_carries_every_size_the_dock_asks_for():
    """`iconutil` is silent about a short iconset; the Dock then scales whatever it
    finds and the result is soft at exactly the size it is looked at most."""
    icns = (CONTENTS / "Resources" / "Marktstadt.icns").read_bytes()
    assert icns[:4] == b"icns"
    # Four bytes of length, then type-tagged chunks. Modern sizes are PNG-in-icns
    # under the ic07..ic14 tags; five point sizes at 1x and 2x is ten entries.
    tags = set(re.findall(rb"(ic\d\d|icp\d)", icns))
    assert len(tags) >= 8, f"nur {len(tags)} Icon-Größen im Bundle: {sorted(tags)}"
    assert len(icns) > 50_000, "verdächtig kleines Icon — vermutlich nur eine Größe"
